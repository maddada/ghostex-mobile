#!/usr/bin/env node
/*
Writes src/screens/settings/search/desktopSettingsWords.generated.ts: for each desktop settings key the phone's
Settings search index names (`catalog: '<key>'` in settingsSearchIndex.ts), the words the desktop's Settings search
finds that setting by: its title, subtitle, choices (labels and values) and hidden search words.

The words come from the Ghostex main repo this app sits in: the Settings catalog crate (packages/settings-catalog)
as `cargo xtask help-generate` writes it to skills/ghostex-help/references/settings-catalog.json, and the crate's
search_keywords.rs for the hidden words (the JSON does not carry them). The phone cannot read either at runtime, so
they are copied here; run this again after the desktop's catalog changes or a `catalog` key is added:

  node scripts/generate-settings-search-words.mjs
*/

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ghostexRoot = path.resolve(mobileRoot, '..', '..', '..');
const catalogFile = path.join(ghostexRoot, 'skills', 'ghostex-help', 'references', 'settings-catalog.json');
const keywordsFile = path.join(ghostexRoot, 'packages', 'settings-catalog', 'src', 'search_keywords.rs');
const indexFile = path.join(mobileRoot, 'src', 'screens', 'settings', 'search', 'settingsSearchIndex.ts');
const outFile = path.join(mobileRoot, 'src', 'screens', 'settings', 'search', 'desktopSettingsWords.generated.ts');

const wanted = [
  ...new Set([...fs.readFileSync(indexFile, 'utf8').matchAll(/\bcatalog: '([^']+)'/g)].map((m) => m[1])),
].sort();
if (wanted.length === 0) throw new Error(`${indexFile} names no catalog keys.`);

const catalog = JSON.parse(fs.readFileSync(catalogFile, 'utf8'));
const byKey = new Map(catalog.settings.map((setting) => [setting.key, setting]));

/** The string literals of a Rust `&["a", "b"]` (or a const holding one). */
function rustStrings(source) {
  return [...source.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => JSON.parse(`"${m[1]}"`));
}

/** `fn <name>(…) { match … { "a" | "b" => X, … _ => &[] } }` of search_keywords.rs, as key → words. */
function keywordTable(rust, fnName, consts) {
  const start = rust.indexOf(`pub fn ${fnName}(`);
  if (start < 0) throw new Error(`search_keywords.rs has no ${fnName}.`);
  const body = rust.slice(start, rust.indexOf('_ => &[]', start));
  if (body.length === 0) throw new Error(`${fnName} in search_keywords.rs has no "_ => &[]" arm.`);
  const table = new Map();
  const code = body.replace(/\/\/[^\n]*/g, '');
  for (const arm of code.matchAll(/((?:"[^"]+"\s*\|?\s*)+)=>\s*(&\[[^\]]*\]|[A-Z_]+)/g)) {
    const words = arm[2].startsWith('&') ? rustStrings(arm[2]) : consts.get(arm[2]);
    if (words === undefined) throw new Error(`search_keywords.rs: unknown const ${arm[2]} in ${fnName}.`);
    for (const key of rustStrings(arm[1])) table.set(key, words);
  }
  return table;
}

const rust = fs.readFileSync(keywordsFile, 'utf8');
const consts = new Map(
  [...rust.matchAll(/const ([A-Z_]+): &\[&str\] = (&\[[^\]]*\]);/g)].map((m) => [m[1], rustStrings(m[2])])
);
const rowWords = keywordTable(rust, 'search_keywords', consts);
const sectionWords = keywordTable(rust, 'section_search_keywords', consts);

const missing = wanted.filter((key) => !byKey.has(key));
if (missing.length > 0) throw new Error(`Not in the desktop's Settings catalog: ${missing.join(', ')}`);

const entries = wanted.map((key) => {
  const setting = byKey.get(key);
  const options = (setting.options ?? []).flatMap((option) => [String(option.label), String(option.value)]);
  return [
    key,
    {
      title: setting.title,
      subtitle: setting.subtitle ?? '',
      options: [...new Set(options)].filter((word) => word.trim() !== ''),
      keywords: [...(rowWords.get(key) ?? []), ...(sectionWords.get(setting.section) ?? [])],
    },
  ];
});

const out = `// Generated by scripts/generate-settings-search-words.mjs from the Ghostex main repo's Settings catalog
// (skills/ghostex-help/references/settings-catalog.json and packages/settings-catalog/src/search_keywords.rs).
// Do not edit by hand: run \`node scripts/generate-settings-search-words.mjs\`.

/** The words the desktop's Settings search finds one setting by. */
export type DesktopSettingWords = {
  readonly title: string;
  readonly subtitle: string;
  /** Its choices' labels and stored values. */
  readonly options: readonly string[];
  /** Its hidden search words, and its group's old names. */
  readonly keywords: readonly string[];
};

export const DESKTOP_SETTINGS_WORDS: Readonly<Record<string, DesktopSettingWords>> = ${JSON.stringify(
  Object.fromEntries(entries),
  null,
  2
)};
`;
fs.writeFileSync(outFile, out);
console.log(`Wrote ${path.relative(mobileRoot, outFile)}: ${entries.length} settings.`);
