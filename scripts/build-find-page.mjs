#!/usr/bin/env node
/*
CDXC:PromptSearch 2026-08-20:
Bundles views/find/find-prompts-main.tsx (the Find page, the GUI for `gx f`, that
this app hosts in a webview) into ONE self-contained HTML document and writes it
as the generated TypeScript module src/find/find-prompts-html.generated.ts. The
app imports that string and feeds it to react-native-webview as
`source={{ html }}`, which sidesteps every platform difference around bundled
file:// assets on iOS and Android. Run after changing views/find, or the Ghostex
main repo's core-ui styles or shared UI the page imports:

  bun run build:find-page          (here)
  bun run build:mobile-find        (from the Ghostex main repo)

The page lives in this repo but still imports shared UI and styles from the
Ghostex main repo it is checked out inside (`@/` is that repo's root), so the
build runs with the main repo's esbuild and resolves every package from the main
repo's node_modules. That keeps one React in the bundle; this app's own
node_modules pin a different React for React Native.
*/

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ghostexRoot = path.resolve(mobileRoot, '..', '..', '..');
const esbuild = createRequire(path.join(ghostexRoot, 'package.json'))('esbuild');
const { checkClientStorage } = await import(
  pathToFileURL(path.join(ghostexRoot, 'tooling', 'client-storage', 'check.mjs')).href
);
checkClientStorage();

const entry = path.join(mobileRoot, 'views', 'find', 'find-prompts-main.tsx');
const outFile = path.join(mobileRoot, 'src', 'find', 'find-prompts-html.generated.ts');

/*
The app's Vite/Bun builds deliberately import SVG source text with an import
attribute. esbuild only accepts the standardized JSON value for a `type`
attribute, so remove that source-only hint in this single-file build; the SVG
dataurl loader below remains compatible with the logo helpers.
*/
const mobileFindTextImportPlugin = {
  name: 'mobile-find-text-imports',
  setup(build) {
    build.onLoad({ filter: /core-ui\/(?:agent-logos\.ts|brand-icons\.tsx)$/ }, async (args) => ({
      contents: (await fs.promises.readFile(args.path, 'utf8')).replace(
        /\s+with\s+\{\s*type:\s*["']text["']\s*\}/g,
        ''
      ),
      loader: args.path.endsWith('.tsx') ? 'tsx' : 'ts',
    }));
  },
};

const result = await esbuild.build({
  bundle: true,
  define: { 'process.env.NODE_ENV': '"production"' },
  entryPoints: [entry],
  format: 'iife',
  jsx: 'automatic',
  // Inline every url() asset so the single HTML document has no external
  // references (webview html sources have no usable base URL).
  loader: {
    '.png': 'dataurl',
    '.svg': 'dataurl',
    '.ttf': 'dataurl',
    '.woff': 'dataurl',
    '.woff2': 'dataurl',
  },
  minify: true,
  outdir: 'out',
  plugins: [mobileFindTextImportPlugin],
  target: ['safari16', 'chrome110'],
  write: false,
});

let js = '';
let css = '';
for (const file of result.outputFiles) {
  if (file.path.endsWith('.js')) js += file.text;
  else if (file.path.endsWith('.css')) css += file.text;
}
if (!js) {
  throw new Error('esbuild produced no JS output for the mobile Find page.');
}

// </script>-shaped strings inside generated JS would end the inline script tag.
const inlineJs = js.replace(/<\/script>/gi, '<\\/script>');
const inlineCss = css.replace(/<\/style>/gi, '<\\/style>');

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover" />
    <title>Ghostex Find Prompts</title>
    <style>
      html,
      body {
        background: #111111;
        height: 100%;
        margin: 0;
        overscroll-behavior: none;
        -webkit-text-size-adjust: 100%;
      }
    </style>
    <style>${inlineCss}</style>
  </head>
  <body>
    <div id="root"></div>
    <script>${inlineJs}</script>
  </body>
</html>
`;

const banner = `// GENERATED by scripts/build-find-page.mjs; do not edit by hand. Source:
// views/find (the Find page) plus the shared UI it imports from the Ghostex main
// repo. Regenerate with \`bun run build:find-page\`.

// eslint-disable-next-line @typescript-eslint/no-inferrable-types
export const FIND_PROMPTS_HTML: string = ${JSON.stringify(html)
  .replace(/\u2028/g, '\\u2028')
  .replace(/\u2029/g, '\\u2029')};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner);
const sizeKb = Math.round(Buffer.byteLength(banner) / 1024);
console.log(
  `Wrote ${path.relative(mobileRoot, outFile)} (${sizeKb} KiB; js ${Math.round(js.length / 1024)} KiB, css ${Math.round(css.length / 1024)} KiB).`
);
