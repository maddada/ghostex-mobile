#!/usr/bin/env node
/*
Writes src/chat/session-chat-agents.generated.ts: the agent ids that have a chat
view, which the phone uses to offer the chat toggle.

This app cannot import the Ghostex main repo's packages/shared/session-chat.ts at
runtime, so the list is emitted from the real export: the module is bundled and
evaluated here (with the main repo's esbuild, from the main repo checkout this
app sits in), so the generated list is the runtime value gxserver and every other
client agree on, not a parsed approximation.

Run after changing SESSION_CHAT_SUPPORTED_AGENTS:

  bun run generate:chat-agents          (here)
  bun run generate:mobile-chat-agents   (from the Ghostex main repo; release builds run this)
*/

import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ghostexRoot = path.resolve(mobileRoot, '..', '..', '..');
const esbuild = createRequire(path.join(ghostexRoot, 'package.json'))('esbuild');
const agentsOutFile = path.join(mobileRoot, 'src', 'chat', 'session-chat-agents.generated.ts');

const agentsBundle = await esbuild.build({
  bundle: true,
  format: 'esm',
  platform: 'node',
  stdin: {
    contents: [
      'export { SESSION_CHAT_SUPPORTED_AGENTS } from "./packages/shared/session-chat";',
      'export { resolveAgentIconId } from "./apps/mobile/app/src/contract/mobileSummary";',
    ].join('\n'),
    loader: 'ts',
    resolveDir: ghostexRoot,
    sourcefile: 'session-chat-agents-entry.ts',
  },
  write: false,
});
const agentsModuleSource = agentsBundle.outputFiles[0]?.text ?? '';
const { SESSION_CHAT_SUPPORTED_AGENTS, resolveAgentIconId } = await import(
  `data:text/javascript;base64,${Buffer.from(agentsModuleSource).toString('base64')}`
);
const supportedAgents = [...SESSION_CHAT_SUPPORTED_AGENTS];
if (supportedAgents.length === 0) {
  throw new Error('packages/shared/session-chat.ts exported no supported Session Chat agents.');
}

/**
 * CDXC:SessionChat 2026-09-16 DECISION:
 * User: the React Native app must support chat for the same agents as the GPUI app.
 * ZCode and OpenClaude were in the generated support list but resolved to terminal in the native app, hiding the chat toggle.
 */
const unrecognizedAgents = supportedAgents.filter(
  (agentId) => resolveAgentIconId(agentId) === 'terminal' || resolveAgentIconId(undefined, agentId) === 'terminal'
);
if (unrecognizedAgents.length > 0) {
  throw new Error(`Mobile agent resolution hides chat for supported agents: ${unrecognizedAgents.join(', ')}`);
}

const agentsModule = `// GENERATED by scripts/generate-chat-agents.mjs; do not edit by hand. Source:
// SESSION_CHAT_SUPPORTED_AGENTS in the Ghostex main repo's packages/shared/session-chat.ts.
// Regenerate with \`bun run generate:chat-agents\`.

export const SESSION_CHAT_SUPPORTED_AGENT_IDS: readonly string[] = ${JSON.stringify(supportedAgents)};
`;

fs.mkdirSync(path.dirname(agentsOutFile), { recursive: true });
fs.writeFileSync(agentsOutFile, agentsModule);
console.log(`Wrote ${path.relative(mobileRoot, agentsOutFile)} (${supportedAgents.length} chat-capable agent ids).`);
